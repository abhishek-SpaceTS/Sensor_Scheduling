import json
import torch
import torch.nn as nn
import torch.optim as optim
from pathlib import Path
from torch.utils.data import DataLoader, TensorDataset

# Get paths
script_dir = Path(__file__).parent.resolve()
project_root = script_dir.parent.parent
labels_dir = project_root / "data" / "processed" / "ai_training_data"

class SensorSchedulerNN(nn.Module):
    """
    The Upgraded Student Neural Network. 
    It now takes 3 features because Priority was removed from the Objective: 
    [Duration, TimeGap (Since last target), SlewRequired]
    """
    def __init__(self):
        super(SensorSchedulerNN, self).__init__()
        self.network = nn.Sequential(
            nn.Linear(3, 32),
            nn.ReLU(),
            nn.Linear(32, 16),
            nn.ReLU(),
            nn.Linear(16, 1),
            nn.Sigmoid()
        )

    def forward(self, x):
        return self.network(x)

def load_complex_datasets(directory):
    """
    Reads JSON Answer Keys generated by CP-SAT.
    Extracts features sequentially to provide the AI with Time and Slew Context!
    """
    X_features = []
    Y_labels = []
    
    files = list(directory.glob("rso_scheduler_output_*.json"))
    if not files:
        return None, None
        
    slew_table_file = directory / "slew_table.json"
    slew_table = None
    if slew_table_file.exists():
        with open(slew_table_file, "r") as f:
            slew_table = json.load(f)
        
    for json_path in files:
        with open(json_path, 'r') as f:
            data = json.load(f)
            
        n_rsos = data["n_rsos"]
        windows = data["windows"]
        schedule = data["schedule"]
        
        # 1. Flatten all candidate windows
        candidates = []
        for rso in range(n_rsos):
            for w_idx, (w_start, w_end) in enumerate(windows[rso]):
                candidates.append({
                    "rso": rso,
                    "w_idx": w_idx,
                    "start": w_start,
                    "end": w_end
                })
                
        # 2. Sort chronologically by start time to mimic sequential decision making
        candidates.sort(key=lambda c: c["start"])
        
        # Create a dictionary of scheduled items for easy lookup
        sched_dict = {(item["rso"], item["window_idx"]): item for item in schedule}
        
        last_scheduled_end = 0.0
        last_rso = None
        
        for c in candidates:
            rso = c["rso"]
            w_idx = c["w_idx"]
            start_time = c["start"]
            end_time = c["end"]
            
            # Duration (normalized up to ~1500s)
            duration = min((end_time - start_time) / 1500.0, 1.0)
            
            # Contextual Features
            if last_rso is None:
                time_gap = 1.0  # Plenty of time
                slew_req = 0.0  # No movement needed
            else:
                actual_gap = start_time - last_scheduled_end
                time_gap = max(min(actual_gap / 1000.0, 1.0), 0.0)
                
                # Retrieve max slew time between these two RSOs
                if slew_table is not None:
                    try:
                        if isinstance(slew_table, list):
                            slew_list = slew_table[last_rso][rso]
                        else:
                            slew_list = slew_table[str(last_rso)][str(rso)]
                        req = max(slew_list) if slew_list else 0
                    except (KeyError, IndexError):
                        req = 0
                else:
                    # Fallback to in-file slew_table if running on old mixed data
                    req = max(data.get("slew_table", {}).get(str(last_rso), {}).get(str(rso), [0]))
                slew_req = min(req / 60.0, 1.0) # Normalize to ~60s
                
            is_scheduled = (rso, w_idx) in sched_dict
            label = 1.0 if is_scheduled else 0.0
            
            X_features.append([duration, time_gap, slew_req])
            Y_labels.append([label])
            
            # Update context if this was scheduled
            if is_scheduled:
                last_scheduled_end = sched_dict[(rso, w_idx)]["end"]
                last_rso = rso

    X_tensor = torch.tensor(X_features, dtype=torch.float32)
    Y_tensor = torch.tensor(Y_labels, dtype=torch.float32)
    return X_tensor, Y_tensor

def train_student():
    print("--- Training the Upgraded AI Student ---")
    
    if not labels_dir.exists():
        print(f"Error: {labels_dir} not found! Run the OR-Tools Batch Solver first.")
        return
        
    # 1. Load Data
    X, Y = load_complex_datasets(labels_dir)
    if X is None:
        print("No training data found.")
        return
        
    print(f"Loaded {len(X)} sequential training examples from {len(list(labels_dir.glob('*.json')))} scenarios.")
    dataset = TensorDataset(X, Y)
    dataloader = DataLoader(dataset, batch_size=32, shuffle=True)
    
    # 2. Initialize the AI
    model = SensorSchedulerNN()
    criterion = nn.BCELoss()
    optimizer = optim.Adam(model.parameters(), lr=0.005)
    
    # 3. Train loop
    epochs = 20 # Faster epochs since we have 20,000 examples now!
    for epoch in range(epochs):
        total_loss = 0
        for batch_X, batch_Y in dataloader:
            optimizer.zero_grad()
            predictions = model(batch_X)
            loss = criterion(predictions, batch_Y)
            total_loss += loss.item()
            loss.backward()
            optimizer.step()
            
        if (epoch + 1) % 5 == 0:
            print(f"Epoch [{epoch+1}/{epochs}], Loss: {total_loss/len(dataloader):.4f}")
            
    print("\nTraining Complete! The AI now understands physics and time context.")
    
    # 4. Final Exam
    print("\n--- AI Final Exam ---")
    # Perfect Target: Long Duration, HUGE Time Gap (Sensor is free), Zero Slew
    perfect_target = torch.tensor([[1.0, 1.0, 0.0]])
    prediction1 = model(perfect_target)
    print(f"AI Probability to schedule a Perfect Free Target: {prediction1.item():.2%}")
    
    # Garbage Target: Short Duration, NO Time Gap (Sensor is busy), HUGE Slew required
    garbage_target = torch.tensor([[0.2, 0.0, 1.0]])
    prediction2 = model(garbage_target)
    print(f"AI Probability to schedule an Impossible Garbage Target: {prediction2.item():.2%}")
    
    # 5. Save Model
    model_path = project_root / "models" / "supervised" / "model_weight.pth"
    model_path.parent.mkdir(parents=True, exist_ok=True)
    torch.save(model.state_dict(), model_path)
    print(f"\n-> Successfully saved Smart AI Brain to {model_path.name}")

if __name__ == "__main__":
    train_student()
